// A 5x7 bitmap font for the luminance label, drawn as clear rectangles so no text API is needed.
#pragma once

#include <windows.h>

#include <cstring>
#include <vector>

// One rectangle per lit font pixel, `cell` screen pixels square, with the text's top left at x, y.
// Only digits, space and the letters of "nits" exist; anything else is left blank.
inline std::vector<RECT> textRects(const char* text, LONG x, LONG y, LONG cell) {
    static constexpr char characters[] = "0123456789nits";
    static constexpr unsigned char rows[][7] = {
        {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E}, // 0
        {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E}, // 1
        {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F}, // 2
        {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E}, // 3
        {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02}, // 4
        {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E}, // 5
        {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E}, // 6
        {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08}, // 7
        {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E}, // 8
        {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C}, // 9
        {0x00, 0x00, 0x16, 0x19, 0x11, 0x11, 0x11}, // n
        {0x04, 0x00, 0x0C, 0x04, 0x04, 0x04, 0x0E}, // i
        {0x08, 0x08, 0x1C, 0x08, 0x08, 0x09, 0x06}, // t
        {0x00, 0x00, 0x0E, 0x10, 0x0E, 0x01, 0x1E}, // s
    };

    std::vector<RECT> rects;
    for (; *text; ++text, x += 6 * cell) { // 5 columns and 1 of spacing
        const char* found = std::strchr(characters, *text);
        if (!found) continue;
        for (int row = 0; row < 7; ++row)
            for (int column = 0; column < 5; ++column)
                if (rows[found - characters][row] & (0x10 >> column)) {
                    const LONG left = x + column * cell, top = y + row * cell;
                    rects.push_back({left, top, left + cell, top + cell});
                }
    }
    return rects;
}
